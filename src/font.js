export const bigWidth = (s, scale = 1) => (s.length * 6 - 1) * scale;
export const smallWidth = (s, scale = 1) => (s.length * 4 - 1) * scale;

function drawGlyphs(ctx, s, x, y, color, scale, shadow, big) {
  const pass = (dx, dy, col) => {
    ctx.fillStyle = col;
    let cx = x;
    for (const ch of String(s).toUpperCase()) {
      if (big) {
        const g = BIG[ch] ?? BIG['?'];
        for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) {
          if (g[r][c] === '1') ctx.fillRect(cx + c * scale + dx, y + r * scale + dy, scale, scale);
        }
        cx += 6 * scale;
      } else {
        const g = SMALL[ch] ?? SMALL['?'];
        for (let k = 0; k < 15; k++) {
          if (g[k] === '1') ctx.fillRect(cx + (k % 3) * scale + dx, y + Math.floor(k / 3) * scale + dy, scale, scale);
        }
        cx += 4 * scale;
      }
    }
  };
  if (shadow) pass(scale, scale, shadow);
  pass(0, 0, color);
}

// Big 5x7 text. `align` is 'left', 'center' or 'right' about x.
export function bigText(ctx, s, x, y, color = '#f4f0e0', { scale = 1, shadow = '#10121c', align = 'left' } = {}) {
  const w = bigWidth(String(s), scale);
  const left = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? x - w : x;
  drawGlyphs(ctx, s, left, y, color, scale, shadow, true);
  return w;
}

// Small 3x5 text.
export function smallText(ctx, s, x, y, color = '#d8d4c4', { scale = 1, shadow = null, align = 'left' } = {}) {
  const w = smallWidth(String(s), scale);
  const left = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? x - w : x;
  drawGlyphs(ctx, s, left, y, color, scale, shadow, false);
  return w;
}
