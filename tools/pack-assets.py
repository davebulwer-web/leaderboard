#!/usr/bin/env python3
"""Packs the Pixellab art in assets/raw into src/assets.js as PNG data URIs,
cropped, with anchor points. Run from the project folder: python3 tools/pack-assets.py"""
import base64, io, json, glob, os
from PIL import Image

RAW = 'assets/raw'

def clean(im, min_px=10):
    """Drop small stray specks (e.g. a ball the animator drew) not joined to the figure."""
    px = im.load(); w, h = im.size
    seen = [[False]*w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if seen[y][x] or px[x, y][3] == 0: continue
            comp, stack = [], [(x, y)]; seen[y][x] = True
            while stack:
                cx, cy = stack.pop(); comp.append((cx, cy))
                for nx, ny in ((cx+1,cy),(cx-1,cy),(cx,cy+1),(cx,cy-1),(cx+1,cy+1),(cx-1,cy-1),(cx+1,cy-1),(cx-1,cy+1)):
                    if 0 <= nx < w and 0 <= ny < h and not seen[ny][nx] and px[nx, ny][3] > 0:
                        seen[ny][nx] = True; stack.append((nx, ny))
            if len(comp) < min_px:
                for cx, cy in comp: px[cx, cy] = (0, 0, 0, 0)
    return im

def uri(im):
    b = io.BytesIO(); im.save(b, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()

out = {}
# Golfer: address + swing + putt frames share one crop so they line up.
frames = {'address': f'{RAW}/golfer-address.png'}
for f in sorted(glob.glob(f'{RAW}/swing-*.png')): frames['swing' + f[-6:-4]] = f
for f in sorted(glob.glob(f'{RAW}/putt-*.png')): frames['putt' + f[-6:-4]] = f
def no_ball(im):
    """The animator sometimes draws a ball (or a trail of dots) out by the clubhead;
    the game draws its own. Drop any small blob lying wholly in that corner."""
    px = im.load(); w, h = im.size
    seen = set()
    for y0 in range(h):
        for x0 in range(w):
            if (x0, y0) in seen or px[x0, y0][3] == 0: continue
            comp, stack = [], [(x0, y0)]; seen.add((x0, y0))
            while stack:
                x, y = stack.pop(); comp.append((x, y))
                for nx, ny in ((x+1,y),(x-1,y),(x,y+1),(x,y-1),(x+1,y+1),(x-1,y-1),(x+1,y-1),(x-1,y+1)):
                    if 0 <= nx < w and 0 <= ny < h and (nx, ny) not in seen and px[nx, ny][3] > 0:
                        seen.add((nx, ny)); stack.append((nx, ny))
            if len(comp) < 80 and all((x >= 84 and y >= 95) or (x >= 74 and y >= 108) for x, y in comp):
                for x, y in comp: px[x, y] = (0, 0, 0, 0)
    return im
ims = {k: clean(no_ball(Image.open(v).convert('RGBA'))) for k, v in frames.items()}
box = None
for im in ims.values():
    b = im.getbbox()
    box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
golfer = {k: uri(im.crop(box)) for k, im in ims.items()}
# Where the ball sits relative to the cropped frames (measured on the address pose).
ball = [90 - box[0], 117 - box[1]]
# Feet: bottom of the address pose, and the golfer's height in pixels (for scaling to the world).
feet = [41 - box[0], 114 - box[1]]

def anchored(path, min_px=6):
    im = clean(Image.open(path).convert('RGBA'), min_px)
    b = im.getbbox(); im = im.crop(b)
    px = im.load(); w, h = im.size
    xs = [x for y in range(h - 3, h) for x in range(w) if px[x, y][3] > 0]
    return {'src': uri(im), 'w': w, 'h': h, 'ax': (min(xs) + max(xs)) / 2 if xs else w / 2, 'ay': h}

sprites = {}
for f in sorted(glob.glob(f'{RAW}/tree-*.png')) + sorted(glob.glob(f'{RAW}/bush-*.png')) + [f'{RAW}/flag.png']:
    sprites[os.path.basename(f)[:-4]] = anchored(f)
backdrops = {os.path.basename(f)[9:-4]: uri(Image.open(f).convert('RGBA')) for f in sorted(glob.glob(f'{RAW}/backdrop-*.png'))}

js = ['// Generated by tools/pack-assets.py from assets/raw (Pixellab art). Do not edit.', '']
js.append(f'export const GOLFER_FRAMES = {json.dumps(golfer)};')
js.append(f'export const GOLFER_BALL = {json.dumps(ball)};')
js.append(f'export const GOLFER_FEET = {json.dumps(feet)};')
js.append('export const GOLFER_PX = 108; // address pose height in pixels, about 1.85 yards')
js.append(f'export const SPRITES = {json.dumps(sprites)};')
js.append(f'export const BACKDROPS = {json.dumps(backdrops)};')
open('src/assets.js', 'w').write('\n'.join(js) + '\n')
print('golfer box', box, 'ball', ball, 'size', os.path.getsize('src/assets.js') // 1024, 'KB')
