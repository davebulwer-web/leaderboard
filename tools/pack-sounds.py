#!/usr/bin/env python3
"""Packs the chosen sound effects (assets/sounds/*.mp3) into src/sounds.js.
To change the selection, run tools/pack-sounds.py --from <folder of .wav files>,
which converts the files listed in PICK to mono MP3 first (needs ffmpeg)."""
import base64, glob, json, os, re, subprocess, sys

# Game event -> source files.
PICK = {
    'driver': ['Driver Shot_1', 'Driver Shot_4', 'Driver Shot_6', 'Driver Shot_9'],
    'iron': ['Iron Shot_2', 'Iron Shot_3', 'Iron Shot_12', 'Iron Shot_13'],
    'chip': ['Chip Shot_1', 'Chip Shot_3', 'Chip Shot_5'],
    'bunker': ['Bunker Shot_5', 'Bunker Shot_6', 'Bunker Shot_10'],
    'putt': ['Putt Shot_1', 'Putt Shot_4', 'Putt Shot_5'],
    'cup': ['Ball in Hole_1', 'Ball in Hole_5', 'Ball in Hole_13'],
    'splash': ['Ball Lands in Water_2', 'Ball Lands in Water_5', 'Ball Lands in Water_10'],
    'tree': ['Ball hit tree_1', 'Ball hit tree_2', 'Ball hit tree_3'],
    'bounce': ['Ball Bounce_1', 'Ball Bounce_4', 'Ball Bounce_7', 'Ball Bounce_9'],
    'clap': ['Golf Clap_1', 'Golf Clap_3', 'Golf Clap_5'],
    'bag': ['Take Club from Bag_2', 'Take Club from Bag_3'],
    'rattle': ['Clubs Rattle_1', 'Clubs Rattle_5'],
}
OUT = 'assets/sounds'
slug = lambda s: re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')

if '--from' in sys.argv:
    src = sys.argv[sys.argv.index('--from') + 1]
    os.makedirs(OUT, exist_ok=True)
    for names in PICK.values():
        for n in names:
            wav = os.path.join(src, n + '.wav')
            # Peak-normalise to -3 dB so every sound starts from the same level.
            r = subprocess.run(['ffmpeg', '-hide_banner', '-i', wav, '-af', 'volumedetect', '-f', 'null', '-'], capture_output=True, text=True)
            peak = float(re.search(r'max_volume: (-?[\d.]+) dB', r.stderr).group(1))
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', wav, '-ac', '1', '-ar', '44100',
                            '-af', f'volume={-3 - peak}dB', '-b:a', '64k', os.path.join(OUT, slug(n) + '.mp3')], check=True)

sounds = {}
for ev, names in PICK.items():
    sounds[ev] = ['data:audio/mpeg;base64,' + base64.b64encode(open(os.path.join(OUT, slug(n) + '.mp3'), 'rb').read()).decode() for n in names]
js = '// Generated by tools/pack-sounds.py from assets/sounds. Do not edit.\n\n'
js += f'export const SOUNDS = {json.dumps(sounds)};\n'
open('src/sounds.js', 'w').write(js)
print('src/sounds.js', len(js) // 1024, 'KB')
